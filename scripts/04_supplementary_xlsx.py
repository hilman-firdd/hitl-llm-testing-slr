"""Step 4. Build the supplementary workbook (one file a reviewer can open without Python).

Inputs : data/*, outputs/prisma_counts.json, outputs/screening_log.csv
Output : outputs/Supplementary_HITL_SLR.xlsx
Sheet 4_Extraction_QA keeps the QA total as an Excel formula so the scores can be checked by hand.
"""
import json

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from common import CODES, DATA, OUT, QA_THRESHOLD, load_studies, read_csv

F = "Arial"
H = Font(name=F, bold=True, color="FFFFFF")
B = Font(name=F, size=10)
FILL = PatternFill("solid", fgColor="1F4E79")
TITLE = "A Systematic Literature Review of Human-in-the-Loop Software Testing with Large Language Models"


def sheet(wb, name, header, rows, widths):
    ws = wb.create_sheet(name)
    ws.append(header)
    for c in ws[1]:
        c.font, c.fill, c.alignment = H, FILL, Alignment(wrap_text=True, vertical="top")
    for r in rows:
        ws.append(r)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.font, c.alignment = B, Alignment(wrap_text=True, vertical="top")
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    return ws


def main():
    P = json.load(open(OUT / "prisma_counts.json"))
    log = read_csv(OUT / "screening_log.csv")
    seeds = read_csv(DATA / "raw" / "citation_search_seeds.csv")
    ft = read_csv(DATA / "decisions" / "fulltext_eligibility.csv")
    records = {r["openalex_id"]: r for r in read_csv(DATA / "raw" / "openalex_records.csv")}
    records.update({r["eid"]: r for r in read_csv(DATA / "raw" / "scopus_records.csv")})
    studies = load_studies()
    oql = open(DATA / "search" / "openalex_oql.txt").read().strip()
    scopus = open(DATA / "search" / "scopus_blocks.txt").read().strip()

    wb = Workbook()
    ws = wb.active
    ws.title = "README"
    for line in [f"Supplementary data: {TITLE}",
                 "Search date: 20 October 2026. Databases: OpenAlex (title and abstract) and Scopus (TITLE-ABS-KEY), plus backward and forward citation searching in OpenAlex.",
                 "1_Search: search strings and counts. 2_Screening: all OpenAlex and Scopus records with duplicate flags, title/abstract and full-text decisions.",
                 "3_CitationSearch: seeds and assessed reports. 4_Extraction_QA: eligible studies; the QA total is a formula.",
                 "5_NotRetrieved: reports that could not be obtained. Codes: " + "; ".join(f"{k} = {v}" for k, v in CODES.items()),
                 "Generated by scripts/04_supplementary_xlsx.py."]:
        ws.append([line])
    ws.column_dimensions["A"].width = 130
    for c in ws["A"]:
        c.font = B
    ws["A1"].font = Font(name=F, bold=True, size=12)

    sheet(wb, "1_Search", ["Date", "Source", "Query / seed", "Filters", "Results"],
          [["2026-10-20", "OpenAlex (title-abstract)", oql, "2021-2026; article or conference paper", P["db_identified"]]]
          + [[s["date"], f"OpenAlex citation search ({s['direction']})", s["seed_openalex_id"], s["filter"], int(s["records_identified"])] for s in seeds]
          + [["2026-10-20", "Scopus (TITLE-ABS-KEY, block queries combined as #1 AND #2 AND #3)", scopus, "2021-2026; article, conference paper; English", P["scopus_identified"]]],
          [12, 30, 90, 30, 10])
    sheet(wb, "2_Screening", ["Source", "Record ID", "DOI", "Year", "Title", "Duplicate of", "Title/abstract decision", "Full-text decision", "Reason"],
          [[r["source"], r["record_id"], r["doi"], r["year"], r["title"], r["duplicate_of"], r["title_abstract"], r["full_text"], r["reason"]] for r in log],
          [10, 20, 28, 6, 60, 20, 12, 12, 40])
    sheet(wb, "3_CitationSearch", ["OpenAlex ID", "Stage", "Decision", "Reason", "Note"],
          [[f"seed {s['seed_openalex_id']} ({s['direction']}, {s['records_identified']} records)", "seed", "", "", s["filter"]] for s in seeds]
          + [[r["record_id"], "assessed" if r["decision"] != "NR" else "sought", r["decision"], CODES.get(r["decision"], ""), r["note"]]
             for r in ft if r["source"] == "citation_search"],
          [40, 10, 10, 40, 50])

    hdr = ["Key", "Record ID (OpenAlex or Scopus EID)", "Authors", "Year", "Title", "Venue", "DOI", "Country (1st author)", "Testing activity", "LLM(s)",
           "Human role(s)", "Intervention point", "Human action", "Evaluation level", "Evaluation detail", "Key finding",
           "Evidence (F=full text, A=abstract)", "QA1", "QA2", "QA3", "QA4", "QA5", "QA6", "QA total", f"Status (threshold {QA_THRESHOLD})"]
    ws = sheet(wb, "4_Extraction_QA", hdr, [], [14, 12, 30, 6, 50, 30, 24, 14, 22, 24, 22, 16, 50, 8, 40, 50, 10] + [6] * 6 + [8, 16])
    for i, s in enumerate(studies, start=2):
        ws.append([s["key"], s["record_id"], s["authors"], s["year"], s["title"], s["venue"], s["doi"], s["country"], s["activity"],
                   s["llm"], s["roles"], s["point"], s["human"], s["evaluation"], s["eval_detail"], s["finding"], s["evidence"], *s["qa"],
                   f"=SUM(R{i}:W{i})", f'=IF(X{i}>={QA_THRESHOLD},"included","excluded (QA)")'])
    n = len(studies) + 1
    ws.append([])
    ws.append(["Included (count)"] + [""] * 22 + [f'=COUNTIF(Y2:Y{n},"included")'])
    ws.append(["Mean QA of included"] + [""] * 22 + [f'=AVERAGEIF(Y2:Y{n},"included",X2:X{n})'])
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.font, c.alignment = B, Alignment(wrap_text=True, vertical="top")

    nr = [r for r in ft if r["decision"] == "NR"]
    sheet(wb, "5_NotRetrieved", ["Record ID", "Source", "DOI", "Year", "Title", "Note"],
          [[r["record_id"], r["source"], records.get(r["record_id"], {}).get("doi", ""), records.get(r["record_id"], {}).get("year", ""),
            records.get(r["record_id"], {}).get("title", ""), r["note"] or "no abstract or full text accessible at search time"] for r in nr],
          [14, 16, 30, 6, 60, 45])
    wb.calculation.fullCalcOnLoad = True
    wb.save(OUT / "Supplementary_HITL_SLR.xlsx")
    print("Saved", OUT / "Supplementary_HITL_SLR.xlsx")


if __name__ == "__main__":
    main()
